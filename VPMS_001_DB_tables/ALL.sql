/* ============================================================
   09. PARKING TICKETS

   Ticket status:
   O  = Open
   PP = Pending Payment
   CL = Closed
   CN = Cancelled
   ============================================================ */

CREATE TABLE dbo.VPMS_PARKING_TICKET
(
    VPT_TICKET_ID                    INT IDENTITY(1,1) NOT NULL,
    VPT_TICKET_NUMBER                VARCHAR(40) NOT NULL,
    VPT_VEHICLE_ID                   VARCHAR(10) NOT NULL,
    VPT_SPACE_ID                     VARCHAR(10) NOT NULL,
    VPT_PARKING_TYPE                 VARCHAR(20) NOT NULL,
    VPT_MONTHLY_CONTRACT_ID          INT NULL,

    VPT_HOURLY_RATE_ID               VARCHAR(10) NULL,
    VPT_DAILY_RATE_ID                VARCHAR(10) NULL,
    VPT_APPLIED_HOURLY_RATE          DECIMAL(12,2) NULL,
    VPT_APPLIED_DAILY_RATE           DECIMAL(12,2) NULL,

    VPT_CUSTOMER_NAME                NVARCHAR(200) NULL,
    VPT_MOBILE_NUMBER                VARCHAR(10) NULL,
    VPT_ENTRY_DESCRIPTION            NVARCHAR(500) NULL,

    VPT_ENTRY_DATE_TIME DATETIME2(0) NOT NULL
        CONSTRAINT DF_VPMS_PARKING_TICKET_ENTRY_DATE_TIME
        DEFAULT (SYSUTCDATETIME()),

    VPT_EXIT_DATE_TIME               DATETIME2(0) NULL,
    VPT_BILLABLE_HOURS               DECIMAL(10,2) NULL,
    VPT_CALCULATED_AMOUNT            DECIMAL(12,2) NULL,
    VPT_FEE_CALCULATED_DATE          DATETIME2(0) NULL,
    VPT_APPLIED_DAILY_THRESHOLD_HOURS INT NULL,

    VPT_TICKET_STATUS VARCHAR(30) NOT NULL
        CONSTRAINT DF_VPMS_PARKING_TICKET_STATUS
        DEFAULT ('O'),

    VPT_ENTRY_OPERATOR_ID INT NOT NULL,
    VPT_EXIT_OPERATOR_ID  INT NULL,

    VPT_CREATED_BY INT NULL,
    VPT_CREATED_DATE DATETIME2(0) NOT NULL
        CONSTRAINT DF_VPMS_PARKING_TICKET_CREATED_DATE
        DEFAULT (SYSUTCDATETIME()),

    VPT_UPDATED_BY INT NULL,
    VPT_UPDATED_DATE DATETIME2(0) NULL,

    CONSTRAINT PK_VPMS_PARKING_TICKET
        PRIMARY KEY (VPT_TICKET_ID),

    CONSTRAINT UQ_VPMS_PARKING_TICKET_NUMBER
        UNIQUE (VPT_TICKET_NUMBER),

    CONSTRAINT CK_VPMS_PARKING_TICKET_NUMBER
        CHECK (LEN(LTRIM(RTRIM(VPT_TICKET_NUMBER))) > 0),

    CONSTRAINT CK_VPMS_PARKING_TICKET_STATUS
        CHECK (VPT_TICKET_STATUS IN ('O', 'PP', 'CL', 'CN')),

    CONSTRAINT CK_VPMS_PARKING_TICKET_PARKING_TYPE
        CHECK (VPT_PARKING_TYPE IN ('DAILY', 'MONTHLY')),

    CONSTRAINT CK_VPMS_PARKING_TICKET_CONTRACT
        CHECK
        (
            (
                VPT_PARKING_TYPE = 'DAILY'
                AND VPT_MONTHLY_CONTRACT_ID IS NULL
            )
            OR
            (
                VPT_PARKING_TYPE = 'MONTHLY'
                AND VPT_MONTHLY_CONTRACT_ID IS NOT NULL
            )
        ),

    CONSTRAINT CK_VPMS_PARKING_TICKET_EXIT_DATE
        CHECK
        (
            VPT_EXIT_DATE_TIME IS NULL
            OR VPT_EXIT_DATE_TIME >= VPT_ENTRY_DATE_TIME
        ),

    CONSTRAINT CK_VPMS_PARKING_TICKET_BILLABLE_HOURS
        CHECK
        (
            VPT_BILLABLE_HOURS IS NULL
            OR VPT_BILLABLE_HOURS >= 0
        ),

    CONSTRAINT CK_VPMS_PARKING_TICKET_CALCULATED_AMOUNT
        CHECK
        (
            VPT_CALCULATED_AMOUNT IS NULL
            OR VPT_CALCULATED_AMOUNT >= 0
        ),

    CONSTRAINT CK_VPMS_PARKING_TICKET_HOURLY_RATE
        CHECK
        (
            VPT_APPLIED_HOURLY_RATE IS NULL
            OR VPT_APPLIED_HOURLY_RATE >= 0
        ),

    CONSTRAINT CK_VPMS_PARKING_TICKET_DAILY_RATE
        CHECK
        (
            VPT_APPLIED_DAILY_RATE IS NULL
            OR VPT_APPLIED_DAILY_RATE >= 0
        ),

    CONSTRAINT CK_VPMS_PARKING_TICKET_THRESHOLD
        CHECK
        (
            VPT_APPLIED_DAILY_THRESHOLD_HOURS IS NULL
            OR VPT_APPLIED_DAILY_THRESHOLD_HOURS BETWEEN 1 AND 24
        ),

    CONSTRAINT CK_VPMS_PARKING_TICKET_MOBILE
        CHECK
        (
            VPT_MOBILE_NUMBER IS NULL
            OR
            (
                DATALENGTH(VPT_MOBILE_NUMBER) = 10
                AND VPT_MOBILE_NUMBER COLLATE Latin1_General_100_BIN2
                    NOT LIKE '%[^0-9]%'
            )
        ),

    CONSTRAINT FK_VPMS_PARKING_TICKET_VEHICLE
        FOREIGN KEY (VPT_VEHICLE_ID)
        REFERENCES dbo.VPMS_PARKINGCUSTOMER_VEHICLE(VPV_VEHICLE_ID),

