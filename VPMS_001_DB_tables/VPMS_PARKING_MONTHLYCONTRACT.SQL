CREATE TABLE dbo.VPMS_PARKING_MONTHLYCONTRACT
(
    VPM_CONTRACT_ID INT IDENTITY(1,1) NOT NULL
        CONSTRAINT PK_VPMS_PARKING_MONTHLYCONTRACT PRIMARY KEY,

    VPM_CONTRACT_NUMBER VARCHAR(40) NOT NULL
        CONSTRAINT UQ_VPMS_PARKING_MONTHLYCONTRACT_CONTRACT_NUMBER UNIQUE,

    VPM_CUSTOMER_ID INT NOT NULL,
    VPM_VEHICLE_ID VARCHAR(10) NOT NULL,
    VPM_MONTHLY_FEE DECIMAL(12,2) NOT NULL,

    VPM_START_DATE DATE NOT NULL,
    VPM_END_DATE DATE NOT NULL,

    VPM_CONTRACT_STATUS VARCHAR(20) NOT NULL
        CONSTRAINT DF_VPMS_PARKING_MONTHLYCONTRACT_CONTRACT_STATUS
        DEFAULT ('A'),


    VPM_CANCELLED_AT DATETIME2(0) NULL,
    VPM_CANCELLED_REASON VARCHAR(500) NULL,

    VPM_CREATED_DATE DATETIME2(0) NOT NULL
        CONSTRAINT DF_PARKING_MONTHLYCONTRACT_CREATED_AT
        DEFAULT (SYSUTCDATETIME()),
    VPM_CREATED_BY INT NULL,

    VPM_UPDATED_DATE DATETIME2(0) NULL,
    VPM_UPDATED_BY INT NULL,

    CONSTRAINT CK_VPMS_PARKING_MONTHLYCONTRACT_MONTHLY_FEE
        CHECK (VPM_MONTHLY_FEE >= 0),

    CONSTRAINT CK_VPMS_PARKING_MONTHLYCONTRACT_START_END_DATES
        CHECK (VPM_END_DATE >= VPM_START_DATE),

    CONSTRAINT CK_VPMS_PARKING_MONTHLYCONTRACT_CONTRACT_STATUS
        CHECK
        (
            VPM_CONTRACT_STATUS IN ('A', 'E', 'CN')
        ),

    CONSTRAINT CK_VPMS_PARKING_MONTHLYCONTRACT_CANCELLATION
        CHECK
        (
            (
                VPM_CONTRACT_STATUS <> 'CN'
                AND VPM_CANCELLED_AT IS NULL
                AND VPM_CANCELLED_REASON IS NULL
            )
            OR
            (
                VPM_CONTRACT_STATUS = 'CN'
                AND VPM_CANCELLED_AT IS NOT NULL
                AND VPM_CANCELLED_REASON IS NOT NULL
                AND LEN(LTRIM(RTRIM(VPM_CANCELLED_REASON))) > 0
            )
        ),

    CONSTRAINT FK_VPMS_PARKING_MONTHLYCONTRACT_CUSTOMER
        FOREIGN KEY (VPM_CUSTOMER_ID)
        REFERENCES dbo.VPMS_PARKING_CUSTOMER(VPC_CUSTOMER_ID),

    CONSTRAINT FK_VPMS_PARKING_MONTHLYCONTRACT_VEHICLE_ID
        FOREIGN KEY (VPM_VEHICLE_ID)
        REFERENCES dbo.VPMS_PARKINGCUSTOMER_VEHICLE(VPV_VEHICLE_ID),

    CONSTRAINT FK_VPMS_PARKING_MONTHLYCONTRACT_CREATED_BY
        FOREIGN KEY (VPM_CREATED_BY)
        REFERENCES dbo.VPMS_PARKING_USER(VPU_USER_ID),

    CONSTRAINT FK_VPMS_PARKING_MONTHLYCONTRACT_UPDATED_BY
        FOREIGN KEY (VPM_UPDATED_BY)
        REFERENCES dbo.VPMS_PARKING_USER(VPU_USER_ID)
);
GO

CREATE UNIQUE INDEX UX_VPMS_PARKING_MONTHLY_CONTRACT_ACTIVE_VEHICLE
    ON dbo.VPMS_PARKING_MONTHLYCONTRACT(VPM_VEHICLE_ID)
    WHERE VPM_CONTRACT_STATUS = 'A';
GO

CREATE INDEX IX_VPMS_PARKING_MONTHLYCONTRACT_CUSTOMER
    ON dbo.VPMS_PARKING_MONTHLYCONTRACT
    (
        VPM_CUSTOMER_ID,
        VPM_CONTRACT_STATUS,
        VPM_END_DATE
    );
GO

CREATE SEQUENCE dbo.VPMS_PARKING_MONTHLYCONTRACT_SEQUENCE
    AS BIGINT
    START WITH 1
    INCREMENT BY 1
    NO CYCLE;
GO