CREATE TABLE dbo.VPMS_PARKING_SPACE
(
    VPS_SPACE_ID        VARCHAR(10) NOT NULL,
    VPS_VEHICLE_TYPE_ID VARCHAR(10) NOT NULL,
    VPS_SPACE_CODE      VARCHAR(30) NOT NULL,
    VPS_SPACE_NAME      VARCHAR(100) NULL,

    VPS_SPACE_STATUS    VARCHAR(20) NOT NULL
        CONSTRAINT DF_VPMS_PARKING_SPACE_STATUS DEFAULT ('AV'),

    VPS_BLOCK_REASON    VARCHAR(500) NULL,

    VPS_CREATED_BY      INT NULL,
    VPS_CREATED_DATE    DATETIME2(0) NOT NULL
        CONSTRAINT DF_VPMS_PARKING_SPACE_CREATED_DATE
        DEFAULT (SYSUTCDATETIME()),

    VPS_UPDATED_BY      INT NULL,
    VPS_UPDATED_DATE    DATETIME2(0) NULL,

    CONSTRAINT PK_VPMS_PARKING_SPACE
        PRIMARY KEY (VPS_SPACE_ID),

    CONSTRAINT UQ_VPMS_PARKING_SPACE_CODE
        UNIQUE (VPS_SPACE_CODE),

    CONSTRAINT FK_VPMS_PARKING_SPACE_VEHICLE_TYPE
        FOREIGN KEY (VPS_VEHICLE_TYPE_ID)
        REFERENCES dbo.VPMS_VEHICLE_TYPE(VVT_VEHICLE_TYPE_ID),

    CONSTRAINT FK_VPMS_PARKING_SPACE_CREATED_BY
        FOREIGN KEY (VPS_CREATED_BY)
        REFERENCES dbo.VPMS_PARKING_USER(VPU_USER_ID),

    CONSTRAINT FK_VPMS_PARKING_SPACE_UPDATED_BY
        FOREIGN KEY (VPS_UPDATED_BY)
        REFERENCES dbo.VPMS_PARKING_USER(VPU_USER_ID)
);
GO

CREATE INDEX IX_VPMS_PARKING_SPACE_ALLOCATION
    ON dbo.VPMS_PARKING_SPACE
    (
        VPS_VEHICLE_TYPE_ID,
        VPS_SPACE_STATUS
    );
GO