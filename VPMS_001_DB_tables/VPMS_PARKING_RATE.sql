CREATE TABLE dbo.VPMS_PARKING_RATE
(
    VPR_RATE_ID         VARCHAR(10) NOT NULL,
    VPR_VEHICLE_TYPE_ID VARCHAR(10) NOT NULL,
    VPR_RATE_NAME       VARCHAR(100) NOT NULL,
    VPR_RATE_AMOUNT     DECIMAL(12,2) NOT NULL,
    VPR_RATE_UNIT       VARCHAR(20) NOT NULL,

    VPR_EFFECTIVE_FROM  DATETIME2(0) NOT NULL
        CONSTRAINT DF_VPMS_PARKING_RATE_EFFECTIVE_FROM
        DEFAULT (SYSUTCDATETIME()),

    VPR_EFFECTIVE_TO    DATETIME2(0) NULL,

    VPR_IS_ACTIVE       CHAR NOT NULL
        CONSTRAINT DF_VPMS_PARKING_RATE_IS_ACTIVE DEFAULT ('A'),

    VPR_CREATED_BY      INT NULL,
    VPR_CREATED_DATE    DATETIME2(0) NOT NULL
        CONSTRAINT DF_VPMS_PARKING_RATE_CREATED_DATE
        DEFAULT (SYSUTCDATETIME()),
		 
    VPR_UPDATED_BY      INT NULL,
    VPR_UPDATED_DATE    DATETIME2(0) NULL,

    CONSTRAINT PK_VPMS_PARKING_RATE
        PRIMARY KEY (VPR_RATE_ID),

	CONSTRAINT CK_VPMS_PARKING_RATE_IS_ACTIVE
        CHECK (VPR_IS_ACTIVE IN ('A', 'I')),

    CONSTRAINT FK_VPMS_PARKING_RATE_VEHICLE_TYPE
        FOREIGN KEY (VPR_VEHICLE_TYPE_ID)
        REFERENCES dbo.VPMS_VEHICLE_TYPE(VVT_VEHICLE_TYPE_ID),

    CONSTRAINT FK_VPMS_PARKING_RATE_CREATED_BY
        FOREIGN KEY (VPR_CREATED_BY)
        REFERENCES dbo.VPMS_PARKING_USER(VPU_USER_ID),

    CONSTRAINT FK_VPMS_PARKING_RATE_UPDATED_BY
        FOREIGN KEY (VPR_UPDATED_BY)
        REFERENCES dbo.VPMS_PARKING_USER(VPU_USER_ID)
);
GO

CREATE UNIQUE INDEX UX_VPMS_PARKING_RATE_IS_ACTIVE_TYPE_UNIT
    ON dbo.VPMS_PARKING_RATE(VPR_VEHICLE_TYPE_ID, VPR_RATE_UNIT)
    WHERE VPR_IS_ACTIVE = 'A';
GO


