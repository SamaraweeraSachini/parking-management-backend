CREATE TABLE dbo.VPMS_PARKING_TICKET
(
    VPT_TICKET_ID                     INT IDENTITY(1,1) NOT NULL,
    VPT_TICKET_NUMBER                 VARCHAR(40) NOT NULL,
    VPT_VEHICLE_ID                    VARCHAR(10) NOT NULL,
    VPT_SPACE_ID                      VARCHAR(10) NOT NULL,
    VPT_PARKING_TYPE                  VARCHAR(20) NOT NULL,
    VPT_MONTHLY_CONTRACT_ID           INT NULL,
    VPT_HOURLY_RATE_ID                VARCHAR(10) NULL,
    VPT_DAILY_RATE_ID                 VARCHAR(10) NULL,
    VPT_APPLIED_HOURLY_RATE           DECIMAL(12,2) NULL,
    VPT_APPLIED_DAILY_RATE            DECIMAL(12,2) NULL,
    VPT_CUSTOMER_NAME                 VARCHAR(200) NULL,
    VPT_MOBILE_NUMBER                 VARCHAR(10) NULL,
    VPT_ENTRY_DESCRIPTION             VARCHAR(500) NULL,

    VPT_ENTRY_DATE_TIME               DATETIME2(0) NOT NULL
        CONSTRAINT DF_VPMS_PARKING_TICKET_ENTRY_DATE_TIME
        DEFAULT (SYSUTCDATETIME()),

    VPT_EXIT_DATE_TIME                DATETIME2(0) NULL,
    VPT_BILLABLE_HOURS                DECIMAL(10,2) NULL,
    VPT_CALCULATED_AMOUNT             DECIMAL(12,2) NULL,
    VPT_FEE_CALCULATED_DATE         DATETIME2(0) NULL,
    VPT_APPLIED_DAILY_THRESHOLD_HOURS  INT NULL,

    VPT_TICKET_STATUS                 VARCHAR(30) NOT NULL
        CONSTRAINT DF_VPMS_PARKING_TICKET_STATUS DEFAULT ('O'),

    VPT_ENTRY_OPERATOR_ID             INT NOT NULL,
    VPT_EXIT_OPERATOR_ID              INT NULL,

    VPT_CREATED_BY                    INT NULL,
    VPT_CREATED_DATE                  DATETIME2(0) NOT NULL
        CONSTRAINT DF_VPMS_PARKING_TICKET_CREATED_DATE
        DEFAULT (SYSUTCDATETIME()),

    VPT_UPDATED_BY                    INT NULL,
    VPT_UPDATED_DATE                  DATETIME2(0) NULL,

    CONSTRAINT PK_VPMS_PARKING_TICKET
        PRIMARY KEY (VPT_TICKET_ID),

    CONSTRAINT UQ_VPMS_PARKING_TICKET_NUMBER
        UNIQUE (VPT_TICKET_NUMBER),

	CONSTRAINT CK_VPMS_PARKING_TICKET_STATUS
        CHECK (VPT_TICKET_STATUS  IN ('O', 'PP', 'CL', 'CN')),

    CONSTRAINT FK_VPMS_PARKING_TICKET_VEHICLE
        FOREIGN KEY (VPT_VEHICLE_ID)
        REFERENCES dbo.VPMS_PARKINGCUSTOMER_VEHICLE(VPV_VEHICLE_ID),

    CONSTRAINT FK_VPMS_PARKING_TICKET_SPACE
        FOREIGN KEY (VPT_SPACE_ID)
        REFERENCES dbo.VPMS_PARKING_SPACE(VPS_SPACE_ID),

    CONSTRAINT FK_VPMS_PARKING_TICKET_CONTRACT
        FOREIGN KEY (VPT_MONTHLY_CONTRACT_ID)
        REFERENCES dbo.VPMS_PARKING_MONTHLYCONTRACT(VPM_CONTRACT_ID),

    CONSTRAINT FK_VPMS_PARKING_TICKET_HOURLY_RATE
        FOREIGN KEY (VPT_HOURLY_RATE_ID)
        REFERENCES dbo.VPMS_PARKING_RATE(VPR_RATE_ID),

    CONSTRAINT FK_VPMS_PARKING_TICKET_DAILY_RATE
        FOREIGN KEY (VPT_DAILY_RATE_ID)
        REFERENCES dbo.VPMS_PARKING_RATE(VPR_RATE_ID),

    CONSTRAINT FK_VPMS_PARKING_TICKET_ENTRY_OPERATOR
        FOREIGN KEY (VPT_ENTRY_OPERATOR_ID)
        REFERENCES dbo.VPMS_PARKING_USER(VPU_USER_ID),

    CONSTRAINT FK_VPMS_PARKING_TICKET_EXIT_OPERATOR
        FOREIGN KEY (VPT_EXIT_OPERATOR_ID)
        REFERENCES dbo.VPMS_PARKING_USER(VPU_USER_ID),

    CONSTRAINT FK_VPMS_PARKING_TICKET_CREATED_BY
        FOREIGN KEY (VPT_CREATED_BY)
        REFERENCES dbo.VPMS_PARKING_USER(VPU_USER_ID),

    CONSTRAINT FK_VPMS_PARKING_TICKET_UPDATED_BY
        FOREIGN KEY (VPT_UPDATED_BY)
        REFERENCES dbo.VPMS_PARKING_USER(VPU_USER_ID)
);
GO

CREATE UNIQUE INDEX UX_VPMS_PARKING_TICKET_OPEN_VEHICLE
    ON dbo.VPMS_PARKING_TICKET(VPT_VEHICLE_ID)
    WHERE VPT_EXIT_DATE_TIME IS NULL;
GO

CREATE UNIQUE INDEX UX_VPMS_PARKING_TICKET_OPEN_SPACE
    ON dbo.VPMS_PARKING_TICKET(VPT_SPACE_ID)
    WHERE VPT_EXIT_DATE_TIME IS NULL;
GO

CREATE INDEX IX_VPMS_PARKING_TICKET_ENTRY_DATE
    ON dbo.VPMS_PARKING_TICKET(VPT_ENTRY_DATE_TIME, VPT_PARKING_TYPE);
GO

CREATE SEQUENCE dbo.VPMS_PARKING_TICKET_SEQUENCE
    AS BIGINT
    START WITH 1
    INCREMENT BY 1
    NO CYCLE;
GO
