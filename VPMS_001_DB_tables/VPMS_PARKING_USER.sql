USE [VPMS_001_DB];
GO

CREATE TABLE dbo.VPMS_PARKING_USER
(
    VPU_USER_ID        INT IDENTITY(1,1) NOT NULL,
    VPU_FIRST_NAME     VARCHAR(100) NOT NULL,
    VPU_LAST_NAME      VARCHAR(100) NOT NULL,
    VPU_FULL_NAME      AS LTRIM(RTRIM(CONCAT(VPU_FIRST_NAME, N' ', VPU_LAST_NAME))),
    VPU_USER_NAME      VARCHAR(100) NOT NULL,
    VPU_PASSWORD_HASH  VARCHAR(500) NOT NULL,
    VPU_USER_ROLE      VARCHAR(2) NOT NULL,

	VPU_IS_ACTIVE CHAR NOT NULL
        CONSTRAINT DF_VPMS_PARKING_USER_IS_ACTIVE DEFAULT ('A'),


    VPU_CREATED_BY     INT NULL,
    VPU_CREATED_DATE   DATETIME2(0) NOT NULL
        CONSTRAINT DF_VPMS_PARKING_USER_CREATED_DATE
        DEFAULT (SYSUTCDATETIME()),

    VPU_UPDATED_BY     INT NULL,
    VPU_UPDATED_DATE   DATETIME2(0) NULL,

    CONSTRAINT PK_VPMS_PARKING_USER
        PRIMARY KEY (VPU_USER_ID),

    CONSTRAINT UQ_VPMS_PARKING_USER_USER_NAME
        UNIQUE (VPU_USER_NAME),

    CONSTRAINT CK_VPMS_PARKING_USER_FIRST_NAME
        CHECK (LEN(LTRIM(RTRIM(VPU_FIRST_NAME))) > 0),

    CONSTRAINT CK_VPMS_PARKING_USER_LAST_NAME
        CHECK (LEN(LTRIM(RTRIM(VPU_LAST_NAME))) > 0),

    CONSTRAINT CK_VPMS_PARKING_USER_USER_NAME
        CHECK (LEN(LTRIM(RTRIM(VPU_USER_NAME))) > 0),

    CONSTRAINT CK_VPMS_PARKING_USER_PASSWORD_HASH
        CHECK (LEN(LTRIM(RTRIM(VPU_PASSWORD_HASH))) > 0),

	CONSTRAINT CK_VPMS_PARKING_USER_IS_ACTIVE
        CHECK (VPU_IS_ACTIVE IN ('A', 'I')),

    CONSTRAINT FK_VPMS_PARKING_USER_ROLE
		FOREIGN KEY (VPU_USER_ROLE)
		REFERENCES dbo.VPMS_USER_ROLE(VPR_ROLE_CODE),

    CONSTRAINT FK_VPMS_PARKING_USER_CREATED_BY
        FOREIGN KEY (VPU_CREATED_BY)
        REFERENCES dbo.VPMS_PARKING_USER(VPU_USER_ID),

    CONSTRAINT FK_VPMS_PARKING_USER_UPDATED_BY
        FOREIGN KEY (VPU_UPDATED_BY)
        REFERENCES dbo.VPMS_PARKING_USER(VPU_USER_ID)
);
GO