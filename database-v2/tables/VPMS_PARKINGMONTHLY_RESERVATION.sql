CREATE TABLE dbo.VPMS_PARKINGMONTHLY_RESERVATION
(
    VPR_RESERVATION_ID INT IDENTITY(1,1) NOT NULL
        CONSTRAINT PK_VPMS_PARKINGMONTHLY_RESERVATION PRIMARY KEY,

    VPR_MONTHLY_PAYMENT_ID INT NOT NULL
        CONSTRAINT UQ_VPMS_PARKINGMONTHLY_RESERVATION_PAYMENT UNIQUE,

    VPR_SPACE_ID INT NOT NULL,
    VPR_EFFECTIVE_FROM_UTC DATETIME2(0) NOT NULL,
    VPR_EFFECTIVE_TO_UTC DATETIME2(0) NOT NULL,

    VPR_CREATED_DATE DATETIME2(0) NOT NULL
        CONSTRAINT DF_VPMS_PARKINGMONTHLY_RESERVATION_CREATED_DATE
        DEFAULT (SYSUTCDATETIME()),

    VPR_CREATED_BY INT NOT NULL,

    CONSTRAINT CK_VPMS_PARKINGMONTHLY_RESERVATION_EFFECTIVE_PERIOD
        CHECK (VPR_EFFECTIVE_TO_UTC > VPR_EFFECTIVE_FROM_UTC),

    CONSTRAINT FK_VPMS_PARKINGMONTHLY_RESERVATION_MONTHLY_PAYMENT
        FOREIGN KEY (VPR_MONTHLY_PAYMENT_ID)
        REFERENCES dbo.VPMS_PARKINGMONTHLY_PAYMENT(VPR_MONTHLY_PAYMENT_ID),

    CONSTRAINT FK_VPMS_PARKINGMONTHLY_RESERVATION_SPACE
        FOREIGN KEY (VPR_SPACE_ID)
        REFERENCES dbo.VPMS_PARKING_SPACE(VPS_SPACE_ID),

    CONSTRAINT FK_VPMS_PARKINGMONTHLY_RESERVATION_CREATED_BY
        FOREIGN KEY (VPR_CREATED_BY)
        REFERENCES dbo.VPMS_PARKING_USER(VPU_USER_ID)
);
GO

CREATE INDEX IX_VPMS_PARKINGMONTHLY_RESERVATION_SpacePeriod
    ON dbo.VPMS_PARKINGMONTHLY_RESERVATION
    (
        VPR_SPACE_ID,
        VPR_EFFECTIVE_FROM_UTC,
        VPR_EFFECTIVE_TO_UTC
    );
GO