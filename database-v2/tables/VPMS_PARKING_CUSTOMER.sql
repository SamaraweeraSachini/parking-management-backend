USE [VPMS_001_DB];
GO

CREATE TABLE dbo.VPMS_PARKING_CUSTOMER
(
    VPC_CUSTOMER_ID INT IDENTITY(1,1) NOT NULL
        CONSTRAINT PK_VPMS_PARKING_CUSTOMER PRIMARY KEY,

    VPC_CUSTOMER_NAME NVARCHAR(200) NOT NULL,
    VPC_MOBILE_NUMBER VARCHAR(10) NOT NULL,
    VPC_EMAIL_ADDRESS NVARCHAR(254) NULL,
    VPC_ADDRESS NVARCHAR(500) NULL,

    VPC_REGISTERED_DATE DATETIME2(0) NOT NULL
        CONSTRAINT DF_VPMS_PARKING_CUSTOMER_REGISTERED_DATE
        DEFAULT (SYSUTCDATETIME()),

    VPC_IS_ACTIVE CHAR NOT NULL
        CONSTRAINT DF_PARKING_CUSTOMER_ACTIVE DEFAULT ('A'),

    VPC_CREATED_DATE DATETIME2(0) NOT NULL
        CONSTRAINT DF_VPMS_PARKING_CUSTOMER_CREATED_DATE
        DEFAULT (SYSUTCDATETIME()),
    VPC_CREATED_BY INT NULL,

    VPC_UPDATED_AT DATETIME2(0) NULL,
    VPC_UPDATED_BY INT NULL,

    CONSTRAINT CK_VPMS_PARKING_CUSTOMER_CUSTOMER_NAME
        CHECK (LEN(LTRIM(RTRIM(VPC_CUSTOMER_NAME))) > 0),

    CONSTRAINT CK_VPMS_PARKING_CUSTOMER_MOBILE_NUMBER
        CHECK
        (
            LEN(LTRIM(RTRIM(VPC_MOBILE_NUMBER))) IN (0, 10)
        ),

	CONSTRAINT CK_VPMS_PARKING_CUSTOMER_CUSTOMER_IS_ACTIVE
        CHECK (VPC_IS_ACTIVE IN ('A', 'I')),

    CONSTRAINT FK_VPMS_PARKING_CUSTOMER_CREATED_BY
        FOREIGN KEY (VPC_CREATED_BY)
        REFERENCES dbo.VPMS_PARKING_USER(VPU_USER_ID),

    CONSTRAINT FK_VPMS_PARKING_CUSTOMER_UPDATED_BY
        FOREIGN KEY (VPC_UPDATED_BY)
        REFERENCES dbo.VPMS_PARKING_USER(VPU_USER_ID)
);
GO

CREATE INDEX IX_VPMS_PARKING_CUSTOMER_SEARCH
    ON dbo.VPMS_PARKING_CUSTOMER(VPC_MOBILE_NUMBER, VPC_CUSTOMER_NAME);
GO