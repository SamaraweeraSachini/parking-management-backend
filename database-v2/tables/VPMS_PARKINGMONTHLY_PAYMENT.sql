CREATE TABLE dbo.VPMS_PARKINGMONTHLY_PAYMENT
(
    VPP_MONTHLY_PAYMENT_ID INT IDENTITY(1,1) NOT NULL
        CONSTRAINT PK_VPMS_PARKINGMONTHLY_PAYMENT PRIMARY KEY,

    VPP_PAYMENT_NUMBER VARCHAR(40) NOT NULL
        CONSTRAINT UQ_VPMS_PARKINGMONTHLY_PAYMENT_NUMBER UNIQUE,

    VPP_CONTRACT_ID INT NOT NULL,
    VPP_PERIOD_START_DATE DATE NOT NULL,
    VPP_PERIOD_END_DATE DATE NOT NULL,

    VPP_AMOUNT DECIMAL(12,2) NOT NULL,
    VPP_PAYMENT_METHOD VARCHAR(20) NOT NULL,

    VPP_PAYMENT_STATUS VARCHAR(20) NOT NULL
        CONSTRAINT DF_VPMS_PARKINGMONTHLY_PAYMENT_STATUS
        DEFAULT ('COMPLETED'),

    VPP_PAYMENT_DATE DATETIME2(0) NOT NULL
        CONSTRAINT DF_VPMS_PARKINGMONTHLY_PAYMENT_DATE
        DEFAULT (SYSUTCDATETIME()),

    VPP_RECEIVED_BY_USER_ID INT NOT NULL,

    VPP_RECEIPT_NUMBER VARCHAR(40) NOT NULL
        CONSTRAINT UQ_VPMS_PARKINGMONTHLY_PAYMENT_RECEIPT_NUMBER UNIQUE,

    VPP_REMARKS NVARCHAR(500) NULL,

    VPP_CREATED_DATE DATETIME2(0) NOT NULL
        CONSTRAINT DF_VPMS_PARKINGMONTHLY_PAYMENT_CREATED_DATE
        DEFAULT (SYSUTCDATETIME()),

    VPP_CREATED_BY INT NULL,
    VPP_UPDATED_DATE DATETIME2(0) NULL,
    VPP_UPDATED_BY INT NULL,

    CONSTRAINT CK_VPMS_PARKINGMONTHLY_PAYMENT_PERIOD_START_END_DATES
        CHECK (VPP_PERIOD_START_DATE >= VPP_PERIOD_END_DATE),

    CONSTRAINT CK_VPMS_PARKINGMONTHLY_PAYMENT_VPP_AMOUNT
        CHECK (VPP_AMOUNT >= 0),

    CONSTRAINT CK_VPMS_PARKINGMONTHLY_PAYMENT_METHOD
        CHECK (VPP_PAYMENT_METHOD IN ('CASH', 'CARD')),

    CONSTRAINT CK_PARKING_MONTHLY_PAYMENT_STATUS
        CHECK
        (
            VPP_PAYMENT_STATUS IN ('COMPLETED', 'CANCELLED', 'REFUNDED')
        ),

    CONSTRAINT FK_VPMS_PARKINGMONTHLY_PAYMENT_CONTRACT
        FOREIGN KEY (VPP_CONTRACT_ID)
        REFERENCES dbo.VPMS_PARKING_MONTHLYCONTRACT(VPM_CONTRACT_ID),

    CONSTRAINT FK_VPMS_PARKINGMONTHLY_PAYMENT_OPERATOR
        FOREIGN KEY (VPP_RECEIVED_BY_USER_ID)
        REFERENCES dbo.VPMS_PARKING_USER(VPU_USER_ID),

    CONSTRAINT FK_VPMS_PARKINGMONTHLY_PAYMENT_CREATED_BY
        FOREIGN KEY (VPP_CREATED_BY)
        REFERENCES dbo.VPMS_PARKING_USER(VPU_USER_ID),

    CONSTRAINT FK_VPMS_PARKINGMONTHLY_PAYMENT_UpdatedBy
        FOREIGN KEY (VPP_UPDATED_BY)
        REFERENCES dbo.VPMS_PARKING_USER(VPU_USER_ID)
);
GO

CREATE UNIQUE INDEX UX_VPMS_PARKINGMONTHLY_PAYMENT_COMPLETED_PERIOD
    ON dbo.VPMS_PARKINGMONTHLY_PAYMENT
    (
        VPP_CONTRACT_ID,
        VPP_PERIOD_START_DATE,
        VPP_PERIOD_END_DATE
    )
    WHERE VPP_PAYMENT_STATUS = 'COMPLETED';
GO

CREATE INDEX IX_VPMS_PARKINGMONTHLY_PAYMENT_COVERAGE
    ON dbo.VPMS_PARKINGMONTHLY_PAYMENT
    (
        VPP_CONTRACT_ID,
        VPP_PAYMENT_STATUS,
        VPP_PERIOD_START_DATE,
        VPP_PERIOD_END_DATE
    );
GO

CREATE INDEX IX_VPMS_PARKINGMONTHLY_PAYMENT_DATE
    ON dbo.VPMS_PARKINGMONTHLY_PAYMENT
    (
        VPP_PAYMENT_DATE,
        VPP_PAYMENT_STATUS
    );
GO