USE [VPMS_001_DB];
GO

CREATE TABLE dbo.VPMS_PARKING_PAYMENT
(
    VPP_PAYMENT_ID          INT IDENTITY(1,1) NOT NULL,
    VPP_PAYMENT_NUMBER      VARCHAR(40) NOT NULL,
    VPP_TICKET_ID           INT NOT NULL,
    VPP_AMOUNT              DECIMAL(12,2) NOT NULL,
    VPP_PAYMENT_METHOD      VARCHAR(20) NOT NULL,

    VPP_PAYMENT_STATUS      VARCHAR(20) NOT NULL
        CONSTRAINT DF_VPMS_PARKING_PAYMENT_STATUS DEFAULT ('COMPLETED'),

    VPP_PAYMENT_DATE_TIME   DATETIME2(0) NOT NULL
        CONSTRAINT DF_VPMS_PARKING_PAYMENT_DATE_TIME
        DEFAULT (SYSUTCDATETIME()),

    VPP_RECEIVED_BY_USER_ID INT NOT NULL,
    VPP_RECEIPT_NUMBER      VARCHAR(40) NOT NULL,
    VPP_REMARKS             NVARCHAR(500) NULL,

    VPP_CREATED_BY          INT NULL,
    VPP_CREATED_DATE        DATETIME2(0) NOT NULL
        CONSTRAINT DF_VPMS_PARKING_PAYMENT_CREATED_DATE
        DEFAULT (SYSUTCDATETIME()),

    VPP_UPDATED_BY          INT NULL,
    VPP_UPDATED_DATE        DATETIME2(0) NULL,

    CONSTRAINT PK_VPMS_PARKING_PAYMENT
        PRIMARY KEY (VPP_PAYMENT_ID),

    CONSTRAINT UQ_VPMS_PARKING_PAYMENT_NUMBER
        UNIQUE (VPP_PAYMENT_NUMBER),

    CONSTRAINT UQ_VPMS_PARKING_PAYMENT_TICKET
        UNIQUE (VPP_TICKET_ID),

    CONSTRAINT UQ_VPMS_PARKING_PAYMENT_RECEIPT
        UNIQUE (VPP_RECEIPT_NUMBER),

    CONSTRAINT FK_VPMS_PARKING_PAYMENT_TICKET
        FOREIGN KEY (VPP_TICKET_ID)
        REFERENCES dbo.VPMS_PARKING_TICKET(VPT_TICKET_ID),

    CONSTRAINT FK_VPMS_PARKING_PAYMENT_RECEIVED_BY
        FOREIGN KEY (VPP_RECEIVED_BY_USER_ID)
        REFERENCES dbo.VPMS_PARKING_USER(VPU_USER_ID),

    CONSTRAINT FK_VPMS_PARKING_PAYMENT_CREATED_BY
        FOREIGN KEY (VPP_CREATED_BY)
        REFERENCES dbo.VPMS_PARKING_USER(VPU_USER_ID),

    CONSTRAINT FK_VPMS_PARKING_PAYMENT_UPDATED_BY
        FOREIGN KEY (VPP_UPDATED_BY)
        REFERENCES dbo.VPMS_PARKING_USER(VPU_USER_ID)
);
GO

CREATE INDEX IX_VPMS_PARKING_PAYMENT_DATE
    ON dbo.VPMS_PARKING_PAYMENT
    (
        VPP_PAYMENT_DATE_TIME,
        VPP_PAYMENT_STATUS
    );
GO

-- Shared by daily and monthly payments.
CREATE SEQUENCE dbo.VPMS_PARKING_PAYMENT_SEQUENCE
    AS BIGINT
    START WITH 1
    INCREMENT BY 1
    NO CYCLE;
GO