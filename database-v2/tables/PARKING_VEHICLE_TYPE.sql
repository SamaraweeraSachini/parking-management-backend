USE [VehicleParkingManagementDB_V2];
GO

CREATE TABLE dbo.PARKING_VEHICLE_TYPE
(
    VehicleTypeID INT IDENTITY(1,1) NOT NULL
        CONSTRAINT PK_PARKING_VEHICLE_TYPE PRIMARY KEY,

    TypeName NVARCHAR(100) NOT NULL
        CONSTRAINT UQ_PARKING_VEHICLE_TYPE_Name UNIQUE,

    WheelCount INT NOT NULL
        CONSTRAINT UQ_PARKING_VEHICLE_TYPE_Wheels UNIQUE,

    Description NVARCHAR(500) NULL,

    ActiveStatus BIT NOT NULL
        CONSTRAINT DF_PARKING_VEHICLE_TYPE_Active DEFAULT (1),

    CreatedAt DATETIME2(0) NOT NULL
        CONSTRAINT DF_PARKING_VEHICLE_TYPE_CreatedAt
        DEFAULT (SYSUTCDATETIME()),

    CreatedBy INT NULL,
    UpdatedAt DATETIME2(0) NULL,
    UpdatedBy INT NULL,

    CONSTRAINT CK_PARKING_VEHICLE_TYPE_Name
        CHECK (LEN(LTRIM(RTRIM(TypeName))) > 0),

    CONSTRAINT CK_PARKING_VEHICLE_TYPE_Wheels
        CHECK (WheelCount IN (2, 3, 4)),

    CONSTRAINT FK_PARKING_VEHICLE_TYPE_CreatedBy
        FOREIGN KEY (CreatedBy)
        REFERENCES dbo.PARKING_USER(UserID),

    CONSTRAINT FK_PARKING_VEHICLE_TYPE_UpdatedBy
        FOREIGN KEY (UpdatedBy)
        REFERENCES dbo.PARKING_USER(UserID)
);
GO