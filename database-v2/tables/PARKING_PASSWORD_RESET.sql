USE [VehicleParkingManagementDB_V2];
GO

CREATE TABLE dbo.PARKING_PASSWORD_RESET
(
    ResetID INT IDENTITY(1,1) NOT NULL
        CONSTRAINT PK_PARKING_PASSWORD_RESET PRIMARY KEY,

    UserID INT NOT NULL,

    TokenHash VARBINARY(32) NOT NULL
        CONSTRAINT UQ_PARKING_PASSWORD_RESET_TokenHash UNIQUE,

    RequestedAt DATETIME2(0) NOT NULL
        CONSTRAINT DF_PARKING_PASSWORD_RESET_RequestedAt
        DEFAULT (SYSUTCDATETIME()),

    ExpiresAt DATETIME2(0) NOT NULL,
    UsedAt DATETIME2(0) NULL,
    IssuedBy INT NULL,

    CONSTRAINT CK_PARKING_PASSWORD_RESET_HashLength
        CHECK (DATALENGTH(TokenHash) = 32),

    CONSTRAINT CK_PARKING_PASSWORD_RESET_Expiry
        CHECK (ExpiresAt > RequestedAt),

    CONSTRAINT CK_PARKING_PASSWORD_RESET_UsedAt
        CHECK
        (
            UsedAt IS NULL
            OR UsedAt >= RequestedAt
        ),

    CONSTRAINT FK_PARKING_PASSWORD_RESET_User
        FOREIGN KEY (UserID)
        REFERENCES dbo.PARKING_USER(UserID),

    CONSTRAINT FK_PARKING_PASSWORD_RESET_IssuedBy
        FOREIGN KEY (IssuedBy)
        REFERENCES dbo.PARKING_USER(UserID)
);
GO

CREATE INDEX IX_PARKING_PASSWORD_RESET_User
    ON dbo.PARKING_PASSWORD_RESET(UserID, RequestedAt);
GO