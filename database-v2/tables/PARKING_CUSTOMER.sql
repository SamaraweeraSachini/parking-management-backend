USE [VehicleParkingManagementDB_V2];
GO

CREATE TABLE dbo.PARKING_CUSTOMER
(
    CustomerID INT IDENTITY(1,1) NOT NULL
        CONSTRAINT PK_PARKING_CUSTOMER PRIMARY KEY,

    CustomerName NVARCHAR(200) NOT NULL,
    MobileNumber VARCHAR(20) NOT NULL,
    EmailAddress NVARCHAR(254) NULL,
    Address NVARCHAR(500) NULL,

    RegisteredDate DATETIME2(0) NOT NULL
        CONSTRAINT DF_PARKING_CUSTOMER_RegisteredDate
        DEFAULT (SYSUTCDATETIME()),

    ActiveStatus BIT NOT NULL
        CONSTRAINT DF_PARKING_CUSTOMER_Active DEFAULT (1),

    CreatedAt DATETIME2(0) NOT NULL
        CONSTRAINT DF_PARKING_CUSTOMER_CreatedAt
        DEFAULT (SYSUTCDATETIME()),

    CreatedBy INT NULL,
    UpdatedAt DATETIME2(0) NULL,
    UpdatedBy INT NULL,

    CONSTRAINT CK_PARKING_CUSTOMER_Name
        CHECK (LEN(LTRIM(RTRIM(CustomerName))) > 0),

    CONSTRAINT CK_PARKING_CUSTOMER_Mobile
        CHECK
        (
            LEN(LTRIM(RTRIM(MobileNumber))) BETWEEN 7 AND 20
        ),

    CONSTRAINT FK_PARKING_CUSTOMER_CreatedBy
        FOREIGN KEY (CreatedBy)
        REFERENCES dbo.PARKING_USER(UserID),

    CONSTRAINT FK_PARKING_CUSTOMER_UpdatedBy
        FOREIGN KEY (UpdatedBy)
        REFERENCES dbo.PARKING_USER(UserID)
);
GO

CREATE INDEX IX_PARKING_CUSTOMER_Search
    ON dbo.PARKING_CUSTOMER(MobileNumber, CustomerName);
GO