USE [VehicleParkingManagementDB_V2];
GO

CREATE TABLE dbo.PARKING_CUSTOMER_VEHICLE
(
    VehicleID INT IDENTITY(1,1) NOT NULL
        CONSTRAINT PK_PARKING_CUSTOMER_VEHICLE PRIMARY KEY,

    CustomerID INT NULL,
    VehicleTypeID INT NOT NULL,

    VehicleNumber VARCHAR(30) NOT NULL
        CONSTRAINT UQ_PARKING_CUSTOMER_VEHICLE_Number UNIQUE,

    VehicleMake NVARCHAR(100) NULL,
    VehicleModel NVARCHAR(100) NULL,
    VehicleColour NVARCHAR(50) NULL,

    ActiveStatus BIT NOT NULL
        CONSTRAINT DF_PARKING_CUSTOMER_VEHICLE_Active DEFAULT (1),

    CreatedAt DATETIME2(0) NOT NULL
        CONSTRAINT DF_PARKING_CUSTOMER_VEHICLE_CreatedAt
        DEFAULT (SYSUTCDATETIME()),

    CreatedBy INT NULL,
    UpdatedAt DATETIME2(0) NULL,
    UpdatedBy INT NULL,

    CONSTRAINT CK_PARKING_CUSTOMER_VEHICLE_Number
        CHECK (LEN(LTRIM(RTRIM(VehicleNumber))) > 0),

    CONSTRAINT FK_PARKING_CUSTOMER_VEHICLE_Customer
        FOREIGN KEY (CustomerID)
        REFERENCES dbo.PARKING_CUSTOMER(CustomerID),

    CONSTRAINT FK_PARKING_CUSTOMER_VEHICLE_Type
        FOREIGN KEY (VehicleTypeID)
        REFERENCES dbo.PARKING_VEHICLE_TYPE(VehicleTypeID),

    CONSTRAINT FK_PARKING_CUSTOMER_VEHICLE_CreatedBy
        FOREIGN KEY (CreatedBy)
        REFERENCES dbo.PARKING_USER(UserID),

    CONSTRAINT FK_PARKING_CUSTOMER_VEHICLE_UpdatedBy
        FOREIGN KEY (UpdatedBy)
        REFERENCES dbo.PARKING_USER(UserID)
);
GO

CREATE INDEX IX_PARKING_CUSTOMER_VEHICLE_Customer
    ON dbo.PARKING_CUSTOMER_VEHICLE(CustomerID, ActiveStatus);
GO