CREATE TABLE dbo.PARKING_MONTHLY_RESERVATION
(
    ReservationID INT IDENTITY(1,1) NOT NULL
        CONSTRAINT PK_PARKING_MONTHLY_RESERVATION PRIMARY KEY,

    MonthlyPaymentID INT NOT NULL
        CONSTRAINT UQ_PARKING_MONTHLY_RESERVATION_Payment UNIQUE,

    SpaceID INT NOT NULL,
    EffectiveFromUTC DATETIME2(0) NOT NULL,
    EffectiveToUTC DATETIME2(0) NOT NULL,

    CreatedAt DATETIME2(0) NOT NULL
        CONSTRAINT DF_PARKING_MONTHLY_RESERVATION_CreatedAt
        DEFAULT (SYSUTCDATETIME()),

    CreatedBy INT NOT NULL,

    CONSTRAINT CK_PARKING_MONTHLY_RESERVATION_Period
        CHECK (EffectiveToUTC > EffectiveFromUTC),

    CONSTRAINT FK_PARKING_MONTHLY_RESERVATION_Payment
        FOREIGN KEY (MonthlyPaymentID)
        REFERENCES dbo.PARKING_MONTHLY_PAYMENT(MonthlyPaymentID),

    CONSTRAINT FK_PARKING_MONTHLY_RESERVATION_Space
        FOREIGN KEY (SpaceID)
        REFERENCES dbo.PARKING_SPACE(SpaceID),

    CONSTRAINT FK_PARKING_MONTHLY_RESERVATION_CreatedBy
        FOREIGN KEY (CreatedBy)
        REFERENCES dbo.PARKING_USER(UserID)
);
GO

CREATE INDEX IX_PARKING_MONTHLY_RESERVATION_SpacePeriod
    ON dbo.PARKING_MONTHLY_RESERVATION
    (
        SpaceID,
        EffectiveFromUTC,
        EffectiveToUTC
    );
GO