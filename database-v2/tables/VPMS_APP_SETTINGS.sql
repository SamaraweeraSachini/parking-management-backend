USE [VPMS_001_DB];
GO

CREATE TABLE dbo.VPMS_PARKINGAPP_SETTINGS
(
    VPS_SETTINGS_ID INT IDENTITY(1,1) NOT NULL
        CONSTRAINT PK_VPMS_PARKINGAPP_SETTINGS PRIMARY KEY,

    VPS_FACILITY_NAME VARCHAR(100) NOT NULL,
    VPS_ADDRESS VARCHAR(300) NULL,
    VPS_CONTACT_NUMBER VARCHAR(10) NULL,
    VPS_RECEIPT_MESSAGE VARCHAR(300) NOT NULL,

    VPS_DAILY_THRESHOLD_HOURS INT NOT NULL
        CONSTRAINT DF_VPMS_PARKINGAPP_SETTINGS_DAILY_THRESHOLD_HOURS DEFAULT (6),

    VPS_MONTHLY_CAPACITY_PERCENTAGE DECIMAL(5,2) NULL,

	VPS_CREATED_DATE DATETIME2(0) NULL,
    VPS_CREATED_BY INT NULL,

    VPS_UPDATED_DATE DATETIME NULL,
    VPS_UPDATED_BY INT NULL,

	VPS_IS_ACTIVE CHAR NOT NULL
        CONSTRAINT DF_VPMS_PARKINGAPP_SETTINGS_IS_ACTIVE DEFAULT ('A')


    CONSTRAINT CK_VPMS_PARKINGAPP_SETTINGS_SINGLETON
        CHECK (VPS_SETTINGS_ID = 1),

    CONSTRAINT CK_VPMS_PARKINGAPP_SETTINGS_NAME
        CHECK (LEN(LTRIM(RTRIM(VPS_FACILITY_NAME))) > 0),

    CONSTRAINT CK_VPMS_PARKINGAPP_SETTINGS_RECEIPT_MESSAGE
        CHECK (LEN(LTRIM(RTRIM(VPS_RECEIPT_MESSAGE))) > 0),

    CONSTRAINT CK_VPMS_PARKINGAPP_SETTINGS_THRESHOLD
        CHECK (VPS_DAILY_THRESHOLD_HOURS BETWEEN 1 AND 24),

    CONSTRAINT CK_VPMS_PARKINGAPP_SETTINGS_MONTHLY_CAPACITY
        CHECK
        (
            VPS_MONTHLY_CAPACITY_PERCENTAGE IS NULL
            OR VPS_MONTHLY_CAPACITY_PERCENTAGE BETWEEN 0 AND 100
        ),

	CONSTRAINT CK_PARKINGAPP_SETTINGS_IS_ACTIVE
        CHECK (VPS_IS_ACTIVE IN ('A', 'I')),

	CONSTRAINT FK_VPMS_PARKINGAPP_SETTINGS_CREATED_BY
        FOREIGN KEY (VPS_CREATED_BY)
        REFERENCES dbo.VPMS_PARKING_USER(VPU_USER_ID),

    CONSTRAINT FK_VPMS_PARKING_APP_SETTINGS_UPDATED_BY
        FOREIGN KEY (VPS_UPDATED_BY)
        REFERENCES dbo.VPMS_PARKING_USER(VPU_USER_ID)
);

GO

INSERT dbo.PARKING_APP_SETTINGS
(
    VPS_SETTINGS_ID,
    VPS_FACILITY_NAME,
    VPS_RECEIPT_MESSAGE,
    VPS_DAILY_THRESHOLD_HOURS,
    VPS_MONTHLY_CAPACITY_PERCENTAGE
)
VALUES
(
    1,
    N'Vehicle Parking',
    N'Thank you for parking with us.',
    6,
    NULL
);
GO
