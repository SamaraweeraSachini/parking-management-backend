CREATE TABLE dbo.VPMS_PARKINGCUSTOMER_VEHICLE
(
    VPV_VEHICLE_ID VARCHAR(10) NOT NULL
        CONSTRAINT PK_VPMS_PARKING_CUSTOMER_VEHICLE PRIMARY KEY,

    VPV_CUSTOMER_ID INT NULL,
    VPV_VEHICLE_TYPE_ID INT NOT NULL,

    VPV_VEHICLE_NUMBER VARCHAR(30) NOT NULL
        CONSTRAINT UQ_VPMS_PARKINGCUSTOMER_VEHICLE_NUMBER UNIQUE,

    VPV_VEHICLE_MAKE VARCHAR(100) NULL,
    VPV_VEHICLE_MODEL VARCHAR(100) NULL,
    VPV_VEHICLE_COLOR VARCHAR(50) NULL,

    VPV_IS_ACTIVE CHAR NOT NULL
        CONSTRAINT DF_VPMS_PARKINGCUSTOMER_VEHICLE_IS_ACTIVE 
		DEFAULT ('A'),
	

    VPV_CREATED_DATE DATETIME2(0) NOT NULL
        CONSTRAINT DF_VPMS_PARKINGCUSTOMER_VEHICLE_CREATED_DATE
        DEFAULT (SYSUTCDATETIME()),
    VPV_CREATED_BY INT NULL,

    VPV_UPDATED_DATE DATETIME2(0) NULL,
    VPV_UPDATED_BY INT NULL,

    CONSTRAINT CK_VPMS_PARKINGCUSTOMER_VEHICLE_NUMBER
        CHECK (LEN(LTRIM(RTRIM(VPV_VEHICLE_NUMBER))) > 0),

	CONSTRAINT CK_VPMSPARKINGCUSTOMER_VEHICLE_IS_ACTIVE
        CHECK (VPV_IS_ACTIVE IN ('A', 'I')),

    CONSTRAINT FK_VPMS_PARKINGCUSTOMER_VEHICLE_CUSTOMER_ID
        FOREIGN KEY (VPV_CUSTOMER_ID)
        REFERENCES dbo.VPMS_PARKING_CUSTOMER(VPC_CUSTOMER_ID),

    CONSTRAINT FK_VPMS_PARKINGCUSTOMER_VEHICLE_TYPE
        FOREIGN KEY (VPV_VEHICLE_TYPE_ID)
        REFERENCES dbo.VPMS_PARKING_VEHICLE_TYPE(VPT_VEHICLE_TYPE_ID),

    CONSTRAINT FK_VPMS_PARKINGCUSTOMER_VEHICLE_CREATED_BY
        FOREIGN KEY (VPV_CREATED_BY)
        REFERENCES dbo.VPMS_PARKING_USER(VPU_USER_ID),

    CONSTRAINT FK_PARKINGCUSTOMER_VEHICLE_UPDATED_BY
        FOREIGN KEY (VPV_UPDATED_BY)
        REFERENCES dbo.VPMS_PARKING_USER(VPU_USER_ID)
);
GO

CREATE INDEX IX_VPMS_PARKINGCUSTOMER_VEHICLE_CUSTOMER_NAME
    ON dbo.VPMS_PARKINGCUSTOMER_VEHICLE(VPV_CUSTOMER_ID, VPV_IS_ACTIVE);
GO