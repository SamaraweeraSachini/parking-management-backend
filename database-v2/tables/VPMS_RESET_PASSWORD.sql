USE [VPMS_001_DB];
GO

CREATE TABLE dbo.VPMS_RESET_PASSWORD
(
    VRP_RESET_ID       INT IDENTITY(1,1) NOT NULL,
    VRP_USER_ID        INT NOT NULL,
    VRP_TOKEN_HASH     VARBINARY(32) NOT NULL,

    VRP_REQUESTED_DATE DATETIME2(0) NOT NULL
        CONSTRAINT DF_VPMS_RESET_PASSWORD_REQUESTED_DATE
        DEFAULT (SYSUTCDATETIME()),

    VRP_EXPIRES_DATE   DATETIME2(0) NOT NULL,
    VRP_USED_DATE      DATETIME2(0) NULL,
    VRP_ISSUED_BY      INT NULL,

    VRP_CREATED_BY     INT NULL,
    VRP_CREATED_DATE   DATETIME2(0) NOT NULL
        CONSTRAINT DF_VPMS_RESET_PASSWORD_CREATED_DATE
        DEFAULT (SYSUTCDATETIME()),

    VRP_UPDATED_BY     INT NULL,
    VRP_UPDATED_DATE   DATETIME2(0) NULL,

    CONSTRAINT PK_VPMS_RESET_PASSWORD
        PRIMARY KEY (VRP_RESET_ID),

    CONSTRAINT UQ_VPMS_RESET_PASSWORD_TOKEN_HASH
        UNIQUE (VRP_TOKEN_HASH),

    CONSTRAINT FK_VPMS_RESET_PASSWORD_USER
        FOREIGN KEY (VRP_USER_ID)
        REFERENCES dbo.VPMS_PARKING_USER(VPU_USER_ID),

    CONSTRAINT FK_VPMS_RESET_PASSWORD_ISSUED_BY
        FOREIGN KEY (VRP_ISSUED_BY)
        REFERENCES dbo.VPMS_PARKING_USER(VPU_USER_ID),

    CONSTRAINT FK_VPMS_RESET_PASSWORD_CREATED_BY
        FOREIGN KEY (VRP_CREATED_BY)
        REFERENCES dbo.VPMS_PARKING_USER(VPU_USER_ID),

    CONSTRAINT FK_VPMS_RESET_PASSWORD_UPDATED_BY
        FOREIGN KEY (VRP_UPDATED_BY)
        REFERENCES dbo.VPMS_PARKING_USER(VPU_USER_ID)
);
GO

CREATE INDEX IX_VPMS_RESET_PASSWORD_USER
    ON dbo.VPMS_RESET_PASSWORD(VRP_USER_ID, VRP_REQUESTED_DATE);
GO