USE [VPMS_001_DB];
GO

CREATE TABLE dbo.VPMS_VEHICLE_TYPE
(
    VVT_VEHICLE_TYPE_ID VARCHAR(10) NOT NULL,
    VVT_TYPE_NAME       VARCHAR(100) NOT NULL,
    VVT_WHEEL_COUNT     INT NOT NULL,
    VVT_DESCRIPTION    VARCHAR(500) NULL,

    VVT_IS_ACTIVE      BIT NOT NULL
        CONSTRAINT DF_VPMS_VEHICLE_TYPE_ACTIVE DEFAULT (A),

    VVT_CREATED_BY     INT NULL,
    VVT_CREATED_DATE   DATETIME2(0) NOT NULL
        CONSTRAINT DF_VPMS_VEHICLE_TYPE_CREATED_DATE
        DEFAULT (SYSUTCDATETIME()),

    VVT_UPDATED_BY     INT NULL,
    VVT_UPDATED_DATE   DATETIME2(0) NULL,

    CONSTRAINT PK_VPMS_VEHICLE_TYPE
        PRIMARY KEY (VVT_VEHICLE_TYPE_ID),

    CONSTRAINT UQ_VPMS_VEHICLE_TYPE_NAME
        UNIQUE (VVT_TYPE_NAME),

    CONSTRAINT UQ_VPMS_VEHICLE_TYPE_WHEELS
        UNIQUE (VVT_WHEEL_COUNT),

    CONSTRAINT CK_VPMS_VEHICLE_TYPE_NAME
        CHECK (LEN(LTRIM(RTRIM(VVT_TYPE_NAME))) > 0),

    CONSTRAINT CK_VPMS_VEHICLE_TYPE_WHEELS
        CHECK (VVT_WHEEL_COUNT IN (2, 3, 4)),

    CONSTRAINT FK_VPMS_VEHICLE_TYPE_CREATED_BY
        FOREIGN KEY (VVT_CREATED_BY)
        REFERENCES dbo.VPMS_PARKING_USER(VPU_USER_ID),

    CONSTRAINT FK_VPMS_VEHICLE_TYPE_UPDATED_BY
        FOREIGN KEY (VVT_UPDATED_BY)
        REFERENCES dbo.VPMS_PARKING_USER(VPU_USER_ID)
);
GO