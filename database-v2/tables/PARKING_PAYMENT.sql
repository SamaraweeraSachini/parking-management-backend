USE [VehicleParkingManagementDB_V2];
GO

CREATE TABLE dbo.PARKING_PAYMENT
(
    PaymentID INT IDENTITY(1,1) NOT NULL
        CONSTRAINT PK_PARKING_PAYMENT PRIMARY KEY,

    PaymentNumber VARCHAR(40) NOT NULL
        CONSTRAINT UQ_PARKING_PAYMENT_Number UNIQUE,

    TicketID INT NOT NULL
        CONSTRAINT UQ_PARKING_PAYMENT_Ticket UNIQUE,

    Amount DECIMAL(12,2) NOT NULL,
    PaymentMethod VARCHAR(20) NOT NULL,

    PaymentStatus VARCHAR(20) NOT NULL
        CONSTRAINT DF_PARKING_PAYMENT_Status
        DEFAULT ('COMPLETED'),

    PaymentDateTime DATETIME2(0) NOT NULL
        CONSTRAINT DF_PARKING_PAYMENT_Date
        DEFAULT (SYSUTCDATETIME()),

    ReceivedByUserID INT NOT NULL,

    ReceiptNumber VARCHAR(40) NOT NULL
        CONSTRAINT UQ_PARKING_PAYMENT_Receipt UNIQUE,

    Remarks NVARCHAR(500) NULL,

    CreatedAt DATETIME2(0) NOT NULL
        CONSTRAINT DF_PARKING_PAYMENT_CreatedAt
        DEFAULT (SYSUTCDATETIME()),

    CreatedBy INT NULL,
    UpdatedAt DATETIME2(0) NULL,
    UpdatedBy INT NULL,

    CONSTRAINT CK_PARKING_PAYMENT_Amount
        CHECK (Amount >= 0),

    CONSTRAINT CK_PARKING_PAYMENT_Method
        CHECK (PaymentMethod IN ('CASH', 'CARD')),

    CONSTRAINT CK_PARKING_PAYMENT_Status
        CHECK
        (
            PaymentStatus IN ('COMPLETED', 'CANCELLED', 'REFUNDED')
        ),

    CONSTRAINT FK_PARKING_PAYMENT_Ticket
        FOREIGN KEY (TicketID)
        REFERENCES dbo.PARKING_TICKET(TicketID),

    CONSTRAINT FK_PARKING_PAYMENT_Operator
        FOREIGN KEY (ReceivedByUserID)
        REFERENCES dbo.PARKING_USER(UserID),

    CONSTRAINT FK_PARKING_PAYMENT_CreatedBy
        FOREIGN KEY (CreatedBy)
        REFERENCES dbo.PARKING_USER(UserID),

    CONSTRAINT FK_PARKING_PAYMENT_UpdatedBy
        FOREIGN KEY (UpdatedBy)
        REFERENCES dbo.PARKING_USER(UserID)
);
GO

CREATE INDEX IX_PARKING_PAYMENT_Date
    ON dbo.PARKING_PAYMENT(PaymentDateTime, PaymentStatus);
GO

-- Shared by daily and monthly payment procedures.
CREATE SEQUENCE dbo.PARKING_PAYMENT_SEQUENCE
    AS BIGINT
    START WITH 1
    INCREMENT BY 1
    NO CYCLE;
GO